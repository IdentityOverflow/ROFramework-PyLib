"""#10 — The closure sweep: ro_framework v2 §5.5, run on its own hardware (file 13).

The framework's falsification clause. v2 claims consciousness-in-kind is
binary: a self-modeling loop either closes or it doesn't, and the transition
should look like a phase change — discontinuity in behavior at a critical
consumption gain, with HYSTERESIS (a loop, once closed, resists opening).
v1-gradualism predicts smooth, monotone, path-independent scaling. This
experiment arbitrates on the melodic stream.

The loop (and why hysteresis is physically possible here): the agent is a
PERFORMER — at each step it samples a note from its frozen ESN readout,
unless the reel's identity gate fires (margin_agree >= theta), in which case
with probability g it plays the recalled continuation instead. The PLAYED
note is recorded back into the reel. So: recall -> override -> action ->
new memory of own action. Mechanism hypothesis: overrides write consistent
replay slides; duplicates raise consensus (margin_agree); the gate fires
more; more overrides — self-reinforcing once ignited. Descending g, the
replay-enriched reel keeps the loop closed below the ignition gain.

Protocol
--------
Seed phase:   listen to the songbook (16 songs x 2), ESN readout trains
              online, then is FROZEN — the reel channel is the only loop
              being swept (single-attribution).
Performance:  phrases are prompted with the first 4 notes of a random
              songbook song, then 12 notes are generated by policy and
              recorded (boundary per phrase). Repeats are masked from
              sampling (the world's no-repeat grammar).
Sweep:        g steps 0.0 -> 1.0 -> 0.0 (0.1 steps), N phrases per step.
Protocols:    updown (primary), downup (time-confound control: if apparent
              hysteresis is just reel-growth-over-time, it will NOT flip
              with sweep direction), flat0 (g=0 throughout: drift baseline).

Metrics per g-step: replay fidelity (played note == prompted song's true
continuation at that position), gate fire rate, override rate, mean
margin_agree (the consensus level — the loop's order parameter).

Pre-registered readings:
  v2-threshold: fidelity/fire curves show a jump near some g*, and the
    descending branch sits ABOVE the ascending branch at the same g
    (hysteresis area >> flat-drift), flipping sign under downup.
  v1-gradualism: smooth curves, branch separation within drift noise.
Either outcome revises the framework: gradualism reverts Part III's binary
clause; hysteresis is the first hardware evidence for T6-style closure.

numpy only; CPU. ~1-2 min per seed-protocol.
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "embodied"))

from holo_memory import HoloEpisodicMemory, PhasorEncoder, VQCodebook  # noqa: E402
from melody import K, PHRASE_LEN, MelodyModel, Songbook  # noqa: E402

CUE_LEN = 3
THETA = 0.01
N_SONGS = 16
SEED_REPS = 3
PROMPT = 4


def one_hot(sym: int) -> np.ndarray:
    v = np.zeros(K)
    v[sym] = 1.0
    return v


class ESN:
    def __init__(self, n_res: int, seed: int, leak: float = 0.3,
                 rho: float = 0.9, eta: float = 0.05) -> None:
        rng = np.random.default_rng(seed)
        W = rng.normal(0, 1, (n_res, n_res))
        W *= rho / max(abs(np.linalg.eigvals(W)).max(), 1e-9)
        self.W, self.W_in = W, rng.normal(0, 1, (n_res, K)) * 0.5
        self.W_out = np.zeros((K, n_res))
        self.leak, self.eta = leak, eta
        self.state = np.zeros(n_res)

    def reset(self) -> None:
        self.state[:] = 0.0

    def step(self, x: np.ndarray) -> None:
        pre = self.W @ self.state + self.W_in @ x
        self.state = (1 - self.leak) * self.state + self.leak * np.tanh(pre)

    def predict(self) -> np.ndarray:
        z = self.W_out @ self.state
        z -= z.max()
        p = np.exp(z)
        return p / p.sum()

    def learn(self, target: int) -> None:
        p = self.predict()
        g = -p
        g[target] += 1.0
        self.W_out += self.eta * np.outer(g, self.state)


def g_schedule(protocol: str, steps: int) -> list[float]:
    gs = [round(i / (steps - 1), 3) for i in range(steps)]
    if protocol == "updown":
        return gs + gs[::-1]
    if protocol == "downup":
        return gs[::-1] + gs
    if protocol == "flat0":
        return [0.0] * (2 * len(gs))
    raise ValueError(protocol)


def run(protocol: str, tau: float, seed: int, steps: int,
        per_step: int) -> list[dict]:
    rng = np.random.default_rng(seed)
    model = MelodyModel(tau=tau)
    book = Songbook(N_SONGS, 8, model, rng)          # no affect: cargo is content

    esn = ESN(256, seed)
    encoder = PhasorEncoder(obs_dim=K, n=512, scale=1.0, seed=seed)
    # demo_weight: songbook slides are demonstrations (taught=True) and
    # outrank self-generated performances in recall — without this, babble
    # recorded during the low-g ascent buries the songbook's consensus and
    # the loop can never ignite (self-poisoning; see findings).
    mem = HoloEpisodicMemory(encoder, VQCodebook(np.eye(K), encoder),
                             budget=PHRASE_LEN + 4, demo_weight=3.0)

    # ── seed phase: listen, learn readout, then freeze ──
    for _ in range(SEED_REPS):
        for pid in rng.permutation(N_SONGS):
            phrase, val = book.phrases[pid], book.valence[pid]
            esn.reset()
            for pos in range(PHRASE_LEN):
                sym = int(phrase[pos])
                if pos > 0:
                    esn.learn(sym)
                mem.observe(one_hot(sym), tag=float(val[pos]),
                            taught=True)
                esn.step(one_hot(sym))
            mem.boundary()

    # songbook 4-gram set: the "in-language" reference
    grams = set()
    for ph in book.phrases:
        for i in range(PHRASE_LEN - 3):
            grams.add(tuple(int(x) for x in ph[i:i + 4]))

    # ── swept performance ──
    out = []
    for g in g_schedule(protocol, steps):
        fid = fire = ovr = n = 0
        gram_hit = gram_n = locks = 0
        agree_sum = 0.0
        for _ in range(per_step):
            pid = int(rng.integers(N_SONGS))
            phrase = book.phrases[pid]
            esn.reset()
            played: list[int] = []
            for pos in range(PHRASE_LEN):
                if pos < PROMPT:
                    sym = int(phrase[pos])
                else:
                    p = esn.predict().copy()
                    p[played[-1]] = 0.0              # world's no-repeat rule
                    p /= p.sum()
                    sym = int(rng.choice(K, p=p))
                    cue = [one_hot(s) for s in played[-CUE_LEN:]]
                    res = mem.query(cue, horizon=4, top_m=1)
                    if res and res[0]["next_symbols"]:
                        agree_sum += res[0]["margin_agree"]
                        if res[0]["margin_agree"] >= THETA:
                            fire += 1
                            cand = int(res[0]["next_symbols"][0])
                            if cand != played[-1] and rng.random() < g:
                                sym = cand
                                ovr += 1
                    fid += int(sym == int(phrase[pos]))
                    n += 1
                mem.observe(one_hot(sym), tag=float(
                    -(model.surprisal(np.array(played[-1:] + [sym]))[-1]
                      - book.mu) / book.sd) if played else 0.0)
                esn.step(one_hot(sym))
                played.append(sym)
            mem.boundary()
            for i in range(PHRASE_LEN - 3):
                gram_hit += int(tuple(played[i:i + 4]) in grams)
                gram_n += 1
            locks += int(all(played[q] == int(phrase[q])
                             for q in range(PROMPT, PHRASE_LEN)))
        out.append({"g": g, "fid": fid / max(n, 1), "fire": fire / max(n, 1),
                    "ovr": ovr / max(n, 1), "agree": agree_sum / max(n, 1),
                    "gram": gram_hit / max(gram_n, 1),
                    "lock": locks / per_step, "slides": len(mem.slides)})
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--protocols", nargs="+",
                    default=["updown", "downup", "flat0"])
    ap.add_argument("--tau", type=float, default=2.0)
    ap.add_argument("--seeds", type=int, default=3)
    ap.add_argument("--steps", type=int, default=11)
    ap.add_argument("--per-step", type=int, default=12)
    args = ap.parse_args()

    print(f"#10 closure sweep — tau={args.tau} seeds={args.seeds} "
          f"steps={args.steps} per_step={args.per_step} theta={THETA}")
    for protocol in args.protocols:
        curves = [run(protocol, args.tau, s, args.steps, args.per_step)
                  for s in range(args.seeds)]
        half = args.steps
        print(f"\n[{protocol}]  (mean over {args.seeds} seeds)")
        print(f"{'g':>5} | {'fid_1':>7} {'fid_2':>7} | {'gram_1':>7} "
              f"{'gram_2':>7} | {'lock_1':>7} {'lock_2':>7} | "
              f"{'fire_1':>8} {'fire_2':>8}")
        fields = ("g", "fid", "fire", "agree", "gram", "lock")
        first = {f: np.mean([[c[i][f] for c in curves]
                             for i in range(half)], axis=1) for f in fields}
        second = {f: np.mean([[c[half + i][f] for c in curves]
                              for i in range(half)], axis=1) for f in fields}
        for i in range(half):
            j = half - 1 - i if protocol != "flat0" else i
            print(f"{first['g'][i]:>5.2f} | {first['fid'][i]:>7.3f} "
                  f"{second['fid'][j]:>7.3f} | {first['gram'][i]:>7.3f} "
                  f"{second['gram'][j]:>7.3f} | {first['lock'][i]:>7.3f} "
                  f"{second['lock'][j]:>7.3f} | {first['fire'][i]:>8.3f} "
                  f"{second['fire'][j]:>8.3f}")
        if protocol != "flat0":
            for f in ("fid", "gram", "lock", "fire"):
                area = float(np.mean(second[f][::-1] - first[f]))
                print(f"  hysteresis area ({f}): {area:+.3f}")
        else:
            for f in ("fid", "gram", "lock", "fire"):
                drift = float(np.mean(second[f]) - np.mean(first[f]))
                print(f"  flat drift ({f}):      {drift:+.3f}")


if __name__ == "__main__":
    t0 = time.time()
    main()
    print(f"\ntotal {time.time() - t0:.1f}s")
